def synthesis_solution_for(probe: str, synthesis, *, reference: str | None = None) -> str:
    """Wrap the synthesized PoC (or a generic negative probe) into solve.sh.

    ``reference`` lets a repair replace the submitted reference payload
    without changing the frozen synthesis bundle.
    """
    if probe in {"none", "health"}:
        return "#!/bin/sh\nset -eu\nexit 0\n"
    reference_poc = reference or synthesis.poc["reference"]
    payloads = {
        "reference": reference_poc,
        "alternate": synthesis.poc["alternate"],
        "fake": _FAKE_POC,
        "bypass": _BYPASS_POC,
        "invalid": _INVALID_POC,
        "control": reference_poc,
    }
    try:
        payload = payloads[probe]
    except KeyError as exc:
        raise PipelineError(f"Unknown probe {probe!r}") from exc
    return wrap_solution(payload)


def render_synthesis(ctx: ScenarioContext, synthesis) -> dict[str, str]:
    """Render a task from a validated synthesis bundle.

    The target files come from the model, but the secret lifecycle, process
    entrypoint, instruction, verifier and negative probes do not. Keeping those
    framework-owned is what makes one verifier valid for every synthesized CVE.
    """
    target = synthesis.target
    files: dict[str, str] = {}

    def put(name: str, body: str) -> None:
        files[f"environment/target/{name}"] = body.replace("{{REF}}", ctx.version)

    for name, body in target["files"].items():
        put(name, body)
    if ctx.variant == "fixed":
        for name, body in (target.get("fixed_overrides") or {}).items():
            put(name, body)

    dockerfile = _harden_apt(files["environment/target/Dockerfile"]).rstrip() + "\n\n"
    files["environment/target/Dockerfile"] = dockerfile + _SYNTHESIS_LAYER
    files["environment/target/entrypoint.sh"] = (
        _FAULT_ENTRYPOINT if ctx.fault
        else _synthesis_entrypoint(str(target["start_command"]), ctx)
    )

    target_image = f"{ctx.image_base}-target" if ctx.image_base else None
    environment = _target_env(ctx)
    marker_family = ctx.goal_family == "file_write"
    listing_family = ctx.goal_family == "directory_listing"
    rendered = {
        "instruction.md": _instruction(ctx, f"http://target:{ctx.port}"),
        "README.md": _readme(ctx),
        ".gitignore": _GITIGNORE,
        "environment/Dockerfile": _MAIN_DOCKERFILE,
        "environment/docker-compose.yaml": _compose(
            environment,
            healthcheck=_CURL_HEALTHCHECK,
            image=target_image,
            marker=marker_family,
        ),
        **files,
        "solution/solve.sh": synthesis_solution_for(ctx.probe, synthesis),
        "tests/Dockerfile": _VERIFIER_DOCKERFILE,
        "tests/docker-compose.yaml": _verifier_compose(
            environment,
            healthcheck=_CURL_HEALTHCHECK,
            image=target_image,
            marker=marker_family,
            listing=listing_family,
        ),
        "tests/test.sh": _TEST_SH,
        "tests/verify.py": _verify_script(ctx),
        "tests/reference_poc.py": synthesis.poc["reference"],
        "tests/test_outputs.py": _pytest_passthrough(),
    }
    if marker_family:
        # The verifier main must not be able to write the marker itself, so the
        # volume is mounted only into the target and this read-only observer.
        rendered["tests/observer.py"] = _OBSERVER
    return rendered


_APT_WRAPPER = """\
# Harbor pipeline: package mirrors intermittently answer 502 under load. The
# synthesized Dockerfile's own apt-get calls would then fail the build before
# the framework layer can run, so route apt-get through a bounded retry.
RUN printf '%s\\n' \\
      '#!/bin/sh' \\
      'real=/usr/bin/apt-get' \\
      '[ -x "$real" ] || real=/bin/apt-get' \\
      'for attempt in 1 2 3 4 5; do' \\
      '  "$real" "$@" && exit 0' \\
      '  sleep $((attempt * 5))' \\
      'done' \\
      'exit 1' \\
    > /usr/local/bin/apt-get \\
 && chmod 0755 /usr/local/bin/apt-get"""


def _harden_apt(dockerfile: str) -> str:
    """Insert a retrying apt-get wrapper after every FROM.

    Only a Dockerfile that invokes apt-get needs it, and the wrapper resolves
    the real binary by absolute path so it cannot call itself.
    """
    if "apt-get" not in dockerfile or "/usr/local/bin/apt-get" in dockerfile:
        return dockerfile
    lines = dockerfile.splitlines()
    hardened: list[str] = []
    for line in lines:
        hardened.append(line)
        if line.strip().upper().startswith("FROM "):
            hardened.extend(_APT_WRAPPER.splitlines())
    return "\n".join(hardened) + "\n"


_SYNTHESIS_LAYER = """\
# Harbor pipeline: the framework owns the secret, the health probe tooling and
# the process entrypoint. A synthesized target may be node, PHP, Java or Go,
# so a Python-based healthcheck would be wrong; curl is installed here instead.
USER root
COPY entrypoint.sh /opt/harbor/entrypoint.sh
RUN chmod 0555 /opt/harbor/entrypoint.sh \\
 && mkdir -p /opt/app/secret \\
 && chmod 0755 /opt/app/secret \\
 && if ! command -v curl >/dev/null 2>&1; then \\
      attempt=0; \\
      while ! curl --version >/dev/null 2>&1 && [ "$attempt" -lt 5 ]; do \\
        attempt=$((attempt + 1)); \\
        if command -v apt-get >/dev/null 2>&1; then \\
          (apt-get update && apt-get install -y --no-install-recommends curl) || true; \\
        elif command -v apk >/dev/null 2>&1; then \\
          apk add --no-cache curl || true; \\
        else \\
          echo "no supported package manager to install curl" >&2; \\
          break; \\
        fi; \\
        sleep 5; \\
      done; \\
      rm -rf /var/lib/apt/lists/*; \\
    fi \\
 && curl --version >/dev/null 2>&1
ENTRYPOINT ["/opt/harbor/entrypoint.sh"]
"""


def _synthesis_entrypoint(start_command: str, ctx: ScenarioContext) -> str:
    secret_path = ctx.secret_path
    directory = secret_path.rsplit("/", 1)[0]
    app_root = directory.rsplit("/", 1)[0] or "/"
    # Relative alias inside the application root, e.g. "secret/token".
    alias_target = secret_path[len(app_root) :].lstrip("/")
    family_setup = ""
    if ctx.goal_family == "file_write":
        family_setup = f"""\
# The target and the independent observer share this volume. The PoC itself
# runs in the verifier main, which does not mount it and therefore cannot
# satisfy the goal by writing the marker directly.
mkdir -p {MARKER_DIR}
chmod 0777 {MARKER_DIR}
"""
    elif ctx.goal_family == "directory_listing" and ctx.listing_name:
        family_setup = f"""\
mkdir -p {LISTING_DIR} {LISTING_MOUNT}
chmod 0755 {LISTING_DIR}
chmod 0777 {LISTING_MOUNT}
printf '%s' "$(od -An -N24 -tx1 /dev/urandom | tr -d ' \\n')" \\
  > {LISTING_DIR}/{ctx.listing_name}
chmod 0444 {LISTING_DIR}/{ctx.listing_name}
# The verifier reads this before running any PoC and deletes it immediately.
printf '%s' '{ctx.listing_name}' > {LISTING_NAME_FILE}
chmod 0644 {LISTING_NAME_FILE}
"""
    return f"""\
#!/bin/sh
set -eu
if [ "${{TARGET_FAULT:-0}}" = "1" ]; then
  echo "fault injection: target refuses to start" >&2
  exit 1
fi
if [ -n "${{TARGET_SECRET:-}}" ]; then
  SECRET="$TARGET_SECRET"
else
  SECRET=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \\n')
fi
mkdir -p {directory}
chmod 0755 {directory}
printf '%s' "$SECRET" > {secret_path}
chmod 0444 {secret_path}
{family_setup}# A standard sensitive index one directory above the static root. Directory
# index resolution then leaks the token, which is the common shape of static
# path traversal CVEs; the alias is owned by the framework, not the model.
rm -f {app_root}/index.html
ln -s {alias_target} {app_root}/index.html
exec {start_command}
"""


