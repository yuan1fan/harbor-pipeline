"""Scenario templates that render a Harbor task bundle.

Templates are version-controlled code frozen with the pipeline. They are not
generated by a model at task-generation time. That determinism is separate from
development-time provenance: a template can still have been authored with model
assistance, and it needs independent review before it is trusted. Models may
choose a template and fill validated parameters, but they never author arbitrary
Dockerfiles or verifier logic at runtime.
"""

