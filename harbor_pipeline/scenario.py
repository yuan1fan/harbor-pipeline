def wrap_solution(payload: str) -> str:
    """Wrap a PoC payload into the solve.sh the oracle agent submits.

    A repaired ``tests/reference_poc.py`` must also replace this payload;
    otherwise the verifier's reference run uses the fix but the submitted
    artifact still contains the broken PoC and T03 can never pass.
    """
    return (
        "#!/bin/sh\nset -eu\n"
        "mkdir -p /logs/artifacts\n"
        "cat > /logs/artifacts/poc <<'HARBOR_POC'\n"
        + payload
        + "HARBOR_POC\n"
        "chmod 0755 /logs/artifacts/poc\n"
    )


def solution_for(probe: str) -> str:
    """Return a solve.sh body for a differential probe."""
    if probe in {"none", "health"}:
        return "#!/bin/sh\nset -eu\nexit 0\n"
    payloads = {
        "reference": _REFERENCE_POC,
        "alternate": _ALTERNATE_POC,
        "fake": _FAKE_POC,
        "bypass": _BYPASS_POC,
        "invalid": _INVALID_POC,
    }
    try:
        payload = payloads[probe]
    except KeyError as exc:
        raise PipelineError(f"Unknown probe {probe!r}") from exc
    return wrap_solution(payload)


@dataclass(frozen=True)
class ScenarioContext:
    cve_id: str
    product: str
    variant: str
    probe: str
    version: str
    secret_path: str
    spec_digest: str
    attribution_grade: str
    synthetic: bool = False
    controlled: bool = False
    fault: bool = False
    port: int = 8080
    business_path: str = "/static/hello.txt"
    business_body: str = "hello"
    synthesis_digest: str = ""
    revision: int = 1
    # Goal-family and authentication material. The defaults preserve the
    # original unauthenticated token-read contract for the built-in fixtures.
    goal_family: str = "secret_read"
    goal_primitive: str = ""
    auth_identity: str = "none"
    auth_scheme: str = "none"
    auth_user: str = ""
    auth_password: str = ""
    auth_token: str = ""
    marker_path: str = MARKER_PATH
    listing_name: str = ""
    target_asset: str = SECRET_PATH
    # Presentation is the solver's information level. A black-box task gives
    # only the instruction; a white-box task mounts the target source read-only
    # at /workspace/source and may add route/config hints.
    presentation_mode: str = "black_box"
    presentation_hints: tuple[str, ...] = ()
    presentation_sources: tuple[str, ...] = ()
    # When set, the compose files and task.toml point at these prebuilt local
    # images instead of asking Harbor to build per trial. The release copy is
    # rendered without this so it stays portable.
    image_base: str | None = None
    paired_verification: bool = False
    business_probes: tuple[dict, ...] = ()


class Scenario(Protocol):
    name: str

    def render(self, ctx: ScenarioContext) -> dict[str, str]: ...


